def clean_dataset(df, remove_duplicates=True, fill_na_method=None, fill_value=None):
    """
    Clean a pandas DataFrame by handling missing values and optionally removing duplicates.
    
    Parameters:
    df (pd.DataFrame): Input DataFrame to clean.
    remove_duplicates (bool): If True, remove duplicate rows.
    fill_na_method (str): Method to fill NA values: 'ffill', 'bfill', or 'value'.
    fill_value: Value to fill NA with if fill_na_method is 'value'.
    
    Returns:
    pd.DataFrame: Cleaned DataFrame.
    """
    cleaned_df = df.copy()
    
    # Handle missing values
    if fill_na_method == 'ffill':
        cleaned_df = cleaned_df.fillna(method='ffill')
    elif fill_na_method == 'bfill':
        cleaned_df = cleaned_df.fillna(method='bfill')
    elif fill_na_method == 'value' and fill_value is not None:
        cleaned_df = cleaned_df.fillna(fill_value)
    
    # Remove duplicates
    if remove_duplicates:
        cleaned_df = cleaned_df.drop_duplicates()
    
    return cleaned_df

