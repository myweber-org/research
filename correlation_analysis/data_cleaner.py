def min_max_scaling(dataframe, column, feature_range=(0, 1)):
    """
    Apply min-max scaling to specified column
    """
    min_val = dataframe[column].min()
    max_val = dataframe[column].max()
    
    if max_val > min_val:
        scaled = (dataframe[column] - min_val) / (max_val - min_val)
